import {expect, test} from '@playwright/test';
test('blog layouts, load-more and FAQ interactions work on mobile', async ({page}) => {
  await page.setViewportSize({width:390,height:844});
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/blog?layout=list');
  await page.getByRole('navigation',{name:'Blog categories'}).getByRole('link',{name:'News',exact:true}).click();
  await expect(page).toHaveURL(/layout=list/);
  await expect(page).toHaveURL(/category=News/);
  await page.getByRole('link',{name:'Read More'}).first().click();
  await expect(page.getByRole('link',{name:'Back to blog'})).toBeVisible();
  await page.goto('/load');
  await expect(page).toHaveURL(/\/load-more$/);
  await expect(page.getByRole('status')).toHaveText('Showing 3 of 8 articles');
  await page.getByRole('button',{name:'Load More',exact:true}).click();
  await expect(page.getByRole('status')).toHaveText('Showing 6 of 8 articles');
  await page.getByRole('button',{name:'Load More',exact:true}).click();
  await expect(page.getByRole('status')).toHaveText('Showing 8 of 8 articles');
  await expect(page.getByRole('button',{name:'Load More',exact:true})).toHaveCount(0);
  await page.goto('/faqs');
  const question = page.getByRole('button',{name:'Do you offer dairy-free or vegan options?'});
  await question.focus();
  await page.keyboard.press('Enter');
  await expect(question).toHaveAttribute('aria-expanded','true');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
  await page.goto('/coming-soon');
  await expect(page.getByRole('heading',{name:'Coming Soon'})).toBeVisible();
  await expect(page.getByLabel('Email address')).toBeVisible();
  await page.goto('/missing-page-for-browser-check');
  await expect(page.getByRole('heading',{name:'Sorry! The Page Not Found'})).toBeVisible();
  await page.getByRole('link',{name:'Back to Home'}).click();
  await expect(page).toHaveURL(/\/$/);
});
