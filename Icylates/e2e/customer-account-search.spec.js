import {expect,test} from '@playwright/test';
test('customer profile, live search and admin separation work end to end',async({page})=>{
  await page.setViewportSize({width:1440,height:1000});
  await page.goto('/register');
  await page.getByLabel('Name',{exact:true}).fill('Profile Customer');
  await page.getByLabel('Email',{exact:true}).fill('profile@e2e.test');
  await page.getByLabel('Password',{exact:true}).fill('Profile-Password-589');
  await page.getByRole('button',{name:'Sign Up',exact:true}).click();
  await expect(page).toHaveURL(/\/$/);
  await expect(page.locator('header a[href^="/admin"]')).toHaveCount(0);
  await page.getByRole('link',{name:'My account',exact:true}).click();
  await page.getByLabel('Name',{exact:true}).fill('Updated Profile');
  await page.getByRole('button',{name:'Save changes'}).click();
  await expect(page.getByRole('status')).toHaveText('Your profile has been updated.');
  await page.reload();
  await expect(page.getByLabel('Name',{exact:true})).toHaveValue('Updated Profile');
  const forbidden=await page.request.get('/api/users');
  expect(forbidden.status()).toBe(403);
  await page.getByRole('button',{name:'Search products',exact:true}).click();
  await page.getByRole('searchbox',{name:'Search products'}).fill('pistachio');
  await page.getByRole('link',{name:/Classic Pistachio Gelato/}).click();
  await expect(page.getByRole('heading',{name:'Classic Pistachio Gelato',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Increase quantity'}).click();
  await page.getByRole('button',{name:'Add to Cart',exact:true}).click();
  await expect(page.locator('header').getByRole('link',{name:'Shopping cart'})).toContainText('2');
  await page.goto('/about');
  await expect(page.getByRole('heading',{name:'About Us',exact:true})).toBeVisible();
  await page.goto('/admin/login');
  await page.getByLabel('Email',{exact:true}).fill('profile@e2e.test');
  await page.getByLabel('Password',{exact:true}).fill('Profile-Password-589');
  await page.getByRole('button',{name:'Sign In',exact:true}).click();
  await expect(page.getByRole('alert').filter({hasText:'Administrator access required'})).toBeVisible();
  await expect(page.getByRole('link',{name:'Create an account'})).toHaveCount(0);
});
